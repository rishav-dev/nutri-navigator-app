import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';

/// A class that contains all theme configurations for the application.
/// Implements Contemporary Campus Minimalism design with Warm Academic Palette
class AppTheme {
  AppTheme._();

  // Warm Academic Palette - Brand colors optimized for campus environments
  static const Color primaryLight =
      Color(0xFFF4B942); // Brand yellow for CTAs and key interactive elements
  static const Color secondaryLight = Color(
      0xFFFF8C42); // Supporting orange for accent elements and secondary actions
  static const Color successLight = Color(
      0xFF4CAF50); // Standard green for positive feedback and goal achievements
  static const Color warningLight =
      Color(0xFFFF9800); // Amber for time-sensitive alerts and budget warnings
  static const Color errorLight =
      Color(0xFFF44336); // Material red for errors and critical alerts
  static const Color backgroundLight = Color(
      0xFFFAFAFA); // Soft off-white that reduces eye strain during extended use
  static const Color surfaceLight =
      Color(0xFFFFFFFF); // Pure white for card backgrounds and content areas
  static const Color textPrimaryLight = Color(
      0xFF212121); // Near-black for optimal readability across all lighting conditions
  static const Color textSecondaryLight =
      Color(0xFF757575); // Medium gray for supporting text and metadata
  static const Color dividerLight =
      Color(0xFFE0E0E0); // Light gray for subtle separation

  // Dark theme adaptations maintaining brand consistency
  static const Color primaryDark = Color(0xFFF4B942); // Consistent brand yellow
  static const Color secondaryDark =
      Color(0xFFFF8C42); // Consistent supporting orange
  static const Color successDark =
      Color(0xFF4CAF50); // Consistent success green
  static const Color warningDark =
      Color(0xFFFF9800); // Consistent warning amber
  static const Color errorDark = Color(0xFFF44336); // Consistent error red
  static const Color backgroundDark =
      Color(0xFF121212); // Material dark background
  static const Color surfaceDark =
      Color(0xFF1E1E1E); // Elevated surface for cards
  static const Color textPrimaryDark =
      Color(0xFFFFFFFF); // High contrast white text
  static const Color textSecondaryDark =
      Color(0xFFB3B3B3); // Medium emphasis gray text
  static const Color dividerDark = Color(0xFF2C2C2C); // Subtle dark dividers

  // Additional semantic colors
  static const Color cardLight = Color(0xFFFFFFFF);
  static const Color cardDark = Color(0xFF1E1E1E);
  static const Color dialogLight = Color(0xFFFFFFFF);
  static const Color dialogDark = Color(0xFF2D2D2D);
  static const Color shadowLight = Color(0x1A000000);
  static const Color shadowDark = Color(0x1AFFFFFF);

  /// Light theme implementing Contemporary Campus Minimalism
  static ThemeData lightTheme = ThemeData(
    brightness: Brightness.light,
    colorScheme: ColorScheme(
      brightness: Brightness.light,
      primary: primaryLight,
      onPrimary: Colors.white,
      primaryContainer: primaryLight.withAlpha(26),
      onPrimaryContainer: textPrimaryLight,
      secondary: secondaryLight,
      onSecondary: Colors.white,
      secondaryContainer: secondaryLight.withAlpha(26),
      onSecondaryContainer: textPrimaryLight,
      tertiary: successLight,
      onTertiary: Colors.white,
      tertiaryContainer: successLight.withAlpha(26),
      onTertiaryContainer: textPrimaryLight,
      error: errorLight,
      onError: Colors.white,
      errorContainer: errorLight.withAlpha(26),
      onErrorContainer: textPrimaryLight,
      surface: surfaceLight,
      onSurface: textPrimaryLight,
      onSurfaceVariant: textSecondaryLight,
      outline: dividerLight,
      outlineVariant: dividerLight.withAlpha(128),
      shadow: shadowLight,
      scrim: Colors.black54,
      inverseSurface: surfaceDark,
      onInverseSurface: textPrimaryDark,
      inversePrimary: primaryDark,
